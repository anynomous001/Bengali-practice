"""Build src/data/vocabulary.ts and vocabulary.md from the topic files in vocab/.

Run from the repo root:  python3 content-drafts/build_vocab.py
Edit the words in content-drafts/vocab/*.py, then run this again.
"""
import json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "vocab"))
import a_people, b_food, c_home, d_nature, e_time, f_city, g_language, h_phrases, i_clinical  # noqa: E402

GROUPS = [
    ("people", "People and body", "Family, jobs, the body and feelings."),
    ("food", "Food and kitchen", "Meals, fish, fruit, vegetables, spices, sweets and snacks."),
    ("home", "Home and things", "The house, what is in it, and what people wear."),
    ("nature", "Nature", "Animals, birds, the natural world, and the seasons."),
    ("time", "Time and colours", "Days, months, the calendar, and colours."),
    ("city", "City and travel", "Places, directions, transport and the market."),
    ("school", "School, work and culture", "Study, work, technology, and festivals."),
    ("words", "Words that do the work", "Verbs, describing words, question words and polite phrases."),
    ("clinical", "Speech, hearing and therapy", "For speech therapists and others who work with Bengali-speaking families."),
]
MODULES = [a_people, b_food, c_home, d_nature, e_time, f_city, g_language, i_clinical]
TOPICS = [t for m in MODULES for t in m.TOPICS]
for t in TOPICS:  # example phrases live in vocab/h_phrases.py
    t["phrases"] = list(t["phrases"]) + list(h_phrases.EXTRA.get(t["id"], []))
unknown = set(h_phrases.EXTRA) - {t["id"] for t in TOPICS}
if unknown: raise SystemExit(f"h_phrases has unknown topics: {unknown}")

BN = re.compile(r"[ঀ-৿]")
RO = re.compile(r"^[a-z][a-z .?!',-]*$")
errors = []
ids = set()
total_words = total_phr = 0
for t in TOPICS:
    if t["id"] in ids: errors.append(f"duplicate topic id {t['id']}")
    ids.add(t["id"])
    if t["group"] not in {g[0] for g in GROUPS}: errors.append(f"{t['id']}: unknown group")
    seen = set()
    n = 0
    for title, words in t["sections"]:
        for w in words:
            if len(w) not in (3, 4): errors.append(f"{t['id']}: bad entry {w}"); continue
            bn, ro, en = w[:3]
            n += 1
            if not BN.search(bn): errors.append(f"{t['id']}: no Bengali in {w}")
            if not RO.match(ro): errors.append(f"{t['id']}: bad romanization {w}")
            if not en.strip(): errors.append(f"{t['id']}: empty meaning {w}")
            if bn in seen: errors.append(f"{t['id']}: duplicate word {bn}")
            seen.add(bn)
    if n < 10: errors.append(f"{t['id']}: only {n} words (the quiz needs 10)")
    seenp = set()
    for p in t["phrases"]:
        if p[0] in seenp: errors.append(f"{t['id']}: duplicate phrase {p[0]}")
        seenp.add(p[0])
        if len(p) != 3 or not BN.search(p[0]) or not RO.match(p[1]): errors.append(f"{t['id']}: bad phrase {p}")
        total_phr += 1
    total_words += n
if errors:
    print("\n".join(errors)); sys.exit(1)

def trip(x): return [x[0], x[1], x[2]]
data = [
    dict(id=t["id"], group=t["group"], title=trip(t["title"]), blurb=t["blurb"],
         sections=[dict(title=s, words=[list(w) for w in ws]) for s, ws in t["sections"]],
         phrases=[list(p) for p in t["phrases"]])
    for t in TOPICS
]
groups = [dict(id=i, title=ti, blurb=b) for i, ti, b in GROUPS]
root = Path(__file__).parent.parent
(Path(__file__).parent / "vocabulary.json").write_text(json.dumps(dict(groups=groups, topics=data), ensure_ascii=False, indent=1))

ts = f'''// Topic vocabulary. Generated by content-drafts/build_vocab.py from content-drafts/vocab/*.py: edit those, not this file.
// Only import this from server code (pages/actions) so the text is never in the public JS bundle.
export type Word = [bn: string, roman: string, en: string, note?: string];
export type Phrase = [bn: string, roman: string, en: string];
export type VocabSection = {{ title: string; words: Word[] }};
export type VocabTopic = {{
  id: string;
  group: string;
  title: [bn: string, roman: string, en: string];
  blurb: string;
  sections: VocabSection[];
  phrases: Phrase[];
}};
export type VocabGroup = {{ id: string; title: string; blurb: string }};

/** How many questions a practice round asks. */
export const VOCAB_QUIZ_LEN = 10;

export const VOCAB_GROUPS: VocabGroup[] = {json.dumps(groups, ensure_ascii=False, indent=1)};

export const VOCAB: VocabTopic[] = {json.dumps(data, ensure_ascii=False, indent=1)};

export const wordCount = (t: VocabTopic) => t.sections.reduce((n, s) => n + s.words.length, 0);
'''
(root / "src/data/vocabulary.ts").write_text(ts)

md = [f"# Vocabulary: review copy\n\n{total_words} words and {total_phr} phrases in {len(TOPICS)} topics. Generated by `build_vocab.py`; edit `content-drafts/vocab/*.py`.\n\nPlease check the Bengali spelling, the romanization (how it sounds in Kolkata) and the English meaning.\n"]
for gid, gtitle, _ in GROUPS:
    md.append(f"\n## {gtitle}\n")
    for t in [x for x in TOPICS if x["group"] == gid]:
        n = sum(len(ws) for _, ws in t["sections"])
        md.append(f"\n### {t['title'][2]} ({t['title'][0]}), {n} words\n\n_{t['blurb']}_\n")
        for s, ws in t["sections"]:
            md.append(f"\n**{s}**\n\n| Bengali | Romanized | English |\n|---|---|---|\n" + "\n".join(f"| {w[0]} | {w[1]} | {w[2]} |" for w in ws) + "\n")
        md.append("\n**Phrases**\n\n" + "\n".join(f"- {p[0]} ({p[1]}): {p[2]}" for p in t["phrases"]) + "\n")
(Path(__file__).parent / "vocabulary.md").write_text("".join(md))
print(f"OK: {len(TOPICS)} topics, {total_words} words, {total_phr} phrases")
for gid, gt, _ in GROUPS:
    ts_ = [t for t in TOPICS if t["group"] == gid]
    print(f"  {gt}: {len(ts_)} topics, {sum(len(ws) for t in ts_ for _, ws in t['sections'])} words")
