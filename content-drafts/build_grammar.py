"""Builds src/data/grammar.ts (app data), content-drafts/grammar.json and the review copy from the topic files in gram/.

Run from the repo root:  python3 content-drafts/build_grammar.py
Each gram/t_*.py file defines TOPICS.
"""
import importlib, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "gram"))
import lib
from lib import VERBS, TENSES, PERSONS, verb_table, c  # re-exported for build_workout.py

ORDER = ["t_purush", "t_kriya", "t_kal", "t_karak", "t_bibhakti", "t_bachan", "t_nishedh", "t_vakya"]
T = []
for name in ORDER:
    T += importlib.import_module(name).TOPICS
dups = []
for t in T:
    for s in t["sections"]:
        for b in s["blocks"]:
            if b["t"] in ("ex", "rule"):
                seen = set()
                for it in b["items"]:
                    if it[0] in seen: dups.append((t["id"], s["id"], it[0]))
                    seen.add(it[0])
            if b["t"] == "mistakes":
                seen = set()
                for it in b["items"]:
                    if it[0] in seen: dups.append((t["id"], s["id"], it[0]))
                    seen.add(it[0])
if dups:
    print("duplicate sentences inside one block (they are React keys):"); [print("  ", d) for d in dups]; raise SystemExit(1)
for t in T:
    assert len({s["id"] for s in t["sections"]}) == len(t["sections"]), t["id"]
    for q in t["exercises"]:
        assert 0 <= q["answer"] < len(q["options"]) and len(q["options"]) >= 2, (t["id"], q["q"])
    for s in t["sections"]:
        for b in s["blocks"]:
            if b["t"] == "table":
                for r in b["rows"]: assert len(r) == len(b["head"]), (t["id"], s["id"], b.get("title"))

ts = '''// Grammar lessons and exercises. Generated by content-drafts/build_grammar.py from content-drafts/gram/*.py: edit those, not this file.
// Only import this from server code (pages/actions) so the text is never in the public JS bundle.
export type Cell = string | { bn: string; ro: string };
export type Block =
  | { t: "p"; text: string }
  | { t: "note"; text: string }
  | { t: "h"; text: string }
  | { t: "list"; title: string | null; ordered: boolean; items: string[] }
  | { t: "rule"; title: string; text: string; items: [string, string, string][] }
  | { t: "mistakes"; title: string; items: [wrongBn: string, wrongRo: string, rightBn: string, rightRo: string, why: string][] }
  | { t: "table"; title: string | null; head: string[]; rows: Cell[][] }
  | { t: "ex"; title: string | null; items: [string, string, string][] };
export type ExerciseKind = "pick" | "fill" | "meaning" | "spot" | "change";
export type Exercise = { kind?: ExerciseKind; inst?: string; q: string; sentence: { bn: string; ro: string } | null; options: Cell[]; answer: number; why: string };
export type GrammarSection = { id: string; title: string; blocks: Block[] };
export type GrammarTopic = {
  id: string;
  title: [bn: string, roman: string, en: string];
  blurb: string;
  sections: GrammarSection[];
  exercises: Exercise[];
};

export const GRAMMAR: GrammarTopic[] = '''
root = Path(__file__).parent.parent
(root / "src/data/grammar.ts").write_text(ts + json.dumps(T, ensure_ascii=False, indent=1) + ";\n")
json.dump(T, open(Path(__file__).parent / "grammar.json", "w"), ensure_ascii=False, indent=1)

def n_ex(t): return sum(len(b["items"]) for s in t["sections"] for b in s["blocks"] if b["t"] in ("ex", "rule"))
print("topics:", len(T), "| sections:", sum(len(t["sections"]) for t in T), "| example sentences:", sum(n_ex(t) for t in T), "| exercises:", sum(len(t["exercises"]) for t in T))
for t in T: print(f"  {t['id']:14} sections={len(t['sections']):2} examples={n_ex(t):3} exercises={len(t['exercises']):2}")
