"""Builds src/data/conjuncts.ts from content-drafts/conjuncts_data.py.  Run from the repo root: python3 content-drafts/build_conjuncts.py
Checks that every example word really contains its conjunct."""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from conjuncts_data import CATEGORIES, CONJ

VIRAMA = "্"
cat_ids = [c["id"] for c in CATEGORIES]
out, seen, bad = [], set(), 0
for n, (cat, letters, words) in enumerate(CONJ):
    assert cat in cat_ids, cat
    parts = letters.split()
    conj = VIRAMA.join(parts)
    if (cat, conj) in seen:
        print("duplicate:", cat, conj); bad += 1
    seen.add((cat, conj))
    ws = []
    for w in words:
        bn, ro, en = w.split("|")
        if conj not in bn:
            print(f"word does not contain {conj}: {bn}"); bad += 1
        if not ro.replace(" ", "").isalpha() or not ro.isascii() or ro != ro.lower() and not ro[0].isupper():
            print("romanization:", ro); bad += 1
        ws.append(dict(bn=bn, ro=ro, en=en))
    out.append(dict(id=f"c{n+1}", cat=cat, conj=conj, parts=parts, words=ws))
if bad:
    sys.exit(f"{bad} problems")
root = Path(__file__).parent.parent
ts = f'''// Bengali conjuncts (যুক্তাক্ষর), grouped by how they are built. Generated by content-drafts/build_conjuncts.py: edit conjuncts_data.py, not this file.
// Only import this from server code (pages/actions) so the content is never in the public JS bundle.
export type ConjCategory = {{ id: string; bn: string; ro: string; en: string; blurb: string; look: string }};
export type ConjWord = {{ bn: string; ro: string; en: string }};
export type Conjunct = {{ id: string; cat: string; conj: string; parts: string[]; words: ConjWord[] }};

export const CONJ_CATEGORIES: ConjCategory[] = {json.dumps(CATEGORIES, ensure_ascii=False, indent=1)};

export const CONJUNCTS: Conjunct[] = {json.dumps(out, ensure_ascii=False, indent=1)};

export const conjunctsOf = (cat: string) => CONJUNCTS.filter((c) => c.cat === cat);
export const getConjCategory = (id: string) => CONJ_CATEGORIES.find((c) => c.id === id);
'''
(root / "src/data/conjuncts.ts").write_text(ts)
words = sum(len(c["words"]) for c in out)
print(f"{len(CATEGORIES)} categories, {len(out)} conjuncts, {words} example words")
for c in CATEGORIES:
    print(f"  {c['id']:9} {sum(1 for x in out if x['cat']==c['id'])}")
