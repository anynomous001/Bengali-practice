for t in T:
    o.append(f"# {t['title'][0]} · {t['title'][1]} · {t['title'][2]}\n")
    o.append(f"_{t['blurb']}_\n")
    for s in t["sections"]:
        o.append(f"## {s['title']}\n")
        for b in s["blocks"]:
            if b["t"] == "p": o.append(b["text"] + "\n")
            elif b["t"] == "note": o.append(f"> **Note:** {b['text']}\n")
            elif b["t"] == "ex":
                if b["title"]: o.append(f"**{b['title']}**\n")
                for bn, ro, en in b["items"]: o.append(f"- {bn} _({ro})_: {en}")
                o.append("")
            elif b["t"] == "table":
                if b["title"]: o.append(f"**{b['title']}**\n")
                o.append("| " + " | ".join(b["head"]) + " |")
                o.append("|" + "---|" * len(b["head"]))
                for r in b["rows"]: o.append("| " + " | ".join(cell(x) for x in r) + " |")
                o.append("")
    o.append("## Practice questions\n")
    for n, q in enumerate(t["exercises"], 1):
        line = f"{n}. {q['q']}"
        if q["sentence"]: line += f" **{q['sentence']['bn']}**"
        o.append(line)
        for k, op in enumerate(q["options"]):
            o.append(f"   - {'ABCD'[k]}) {cell(op)}" + ("  ✔" if k == q["answer"] else ""))
        o.append(f"   - _Why:_ {q['why']}")
    o.append("\n---\n")
open("content-drafts/grammar.md", "w").write("\n".join(o))
print(len("\n".join(o)), "chars")
